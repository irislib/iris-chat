import { test, expect } from './fixtures'
import { generateSecretKey, getPublicKey, nip19 } from 'nostr-tools'
import { nhashEncode } from '@hashtree/core'

for (const group of [false,true]) test(`${group ? 'group' : 'direct'} composer mentions, emoji, links and attachment previews`,async({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'Go',exact:true}).click()
  await page.getByRole('button',{name:'New Chat',exact:true}).click()
  await page.getByPlaceholder('Paste invite link').fill(nip19.npubEncode('c'.repeat(64)))
  const input = page.getByPlaceholder('Type a message...')
  await expect(input).toBeVisible()
  if(group){
    await page.getByRole('button',{name:'New Chat',exact:true}).click()
    await page.getByRole('button',{name:'Create Group',exact:true}).click()
    const create=page.getByTestId('create-group-view')
    await create.getByTestId('create-group-member').first().click()
    await create.getByTestId('create-group-next').click()
    await page.getByPlaceholder('Enter group name...').fill('Weekend plans')
    await create.getByTestId('create-group-submit').click()
    await expect(page).toHaveURL(/#group-/)
  }
  await input.fill('@')
  const menu=page.getByRole('listbox',{name:'Mention someone'})
  await expect(menu).toBeVisible()
  expect(await menu.getByRole('option').count()).toBeGreaterThanOrEqual(2)
  const label=(await menu.getByRole('option').first().innerText()).trim()
  await input.press('ArrowDown');await input.press('ArrowUp')
  await page.screenshot({path:`work/web-mentions-${group?'group':'direct'}.png`})
  await input.press('Enter')
  await expect(input).toHaveValue(label+' ')
  await expect(page.locator('.message-content')).toHaveCount(0)
  await input.pressSequentially(':sm')
  await expect(page.getByRole('listbox',{name:'Emoji suggestions'})).toBeVisible()
  await page.screenshot({path:`work/web-emoji-${group?'group':'direct'}.png`})
  await input.press('Tab')
  await expect(input).not.toHaveValue(/:sm/)
  await input.press('Enter')
  const mention=page.locator('.message-content a.message-mention').last()
  await expect(mention).toHaveText(label)
  await expect(mention).toHaveAttribute('href',/#profile-[a-f0-9]{64}/)
  await expect(mention).toHaveCSS('cursor','pointer')
  await expect(mention).toHaveCSS('color','rgb(255, 255, 255)')
  await expect(input).toHaveValue('')
  await input.fill(':thumbsup:')
  await expect(input).toHaveValue('👍')
  await input.fill(':sm')
  await input.press('Escape')
  await expect(page.getByRole('listbox')).toHaveCount(0)
  await expect(input).toHaveValue(':sm')
  await input.fill('https://example.com')
  await input.press('Enter')
  await expect(page.locator('.message-content a[href="https://example.com"]').last()).toHaveCSS('cursor','pointer')
  const hash=nhashEncode({hash:new Uint8Array(32).fill(1)})
  await input.fill(`Caption ${hash}`);await input.press('Enter')
  await expect(page.getByRole('button').filter({hasText:'Caption Attachment'}).first()).toBeVisible()
  await page.screenshot({path:`work/web-completions-sent-${group?'group':'direct'}.png`})
  if(group){
    await page.getByRole('button',{name:'Chat menu',exact:true}).click()
    await page.getByRole('button',{name:'Mute notifications',exact:true}).click()
    const toggle=page.getByRole('checkbox',{name:'Notify me when mentioned'})
    await expect(toggle).toBeChecked();await toggle.uncheck();await expect(toggle).not.toBeChecked()
    await expect(page.getByRole('button',{name:'Always',exact:true})).toBeEnabled()
    await page.screenshot({path:'work/web-mention-mute.png'})
    await page.getByRole('button',{name:'Always',exact:true}).click()
    await expect(page.getByRole('dialog',{name:'Mute notifications',exact:true})).not.toBeVisible()
    await page.reload();await page.getByRole('button',{name:'Chat menu',exact:true}).click()
    await page.getByRole('button',{name:'Muted notifications',exact:true}).click()
    await expect(page.getByRole('checkbox',{name:'Notify me when mentioned'})).not.toBeChecked()
  }
})

test.describe('narrow touch composer',()=>{
  test.use({viewport:{width:390,height:844},hasTouch:true,isMobile:true,userAgent:"Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 Version/18.0 Mobile/15E148 Safari/604.1"})
  test('filters mentions, selects by touch, and keeps IME Enter from sending',async({page})=>{
    await page.goto('/')
    await page.getByRole('button',{name:'Go',exact:true}).click()
    await page.getByRole('button',{name:'New Chat',exact:true}).click()
    await page.getByPlaceholder('Paste invite link').fill(nip19.npubEncode('c'.repeat(64)))
    const input=page.getByPlaceholder('Type a message...')
    await expect(input).toBeVisible()
    const frame = await input.boundingBox()
    await input.fill('@')
    await expect.poll(() => input.boundingBox()).toEqual(frame)
    const menu=page.getByRole('listbox',{name:'Mention someone'})
    const label=(await menu.getByRole('option').first().innerText()).trim()
    await input.fill(label.slice(0,4))
    await expect(menu).toBeVisible()
    await page.screenshot({path:'work/web-mentions-touch.png'})
    await menu.getByRole('option').filter({hasText:label}).first().tap()
    await expect(input).toHaveValue(label+' ')
    await expect(input).toBeFocused()
    await input.dispatchEvent('compositionstart')
    await input.fill(':sm')
    await input.dispatchEvent('keydown',{key:'Enter',keyCode:229,isComposing:true,bubbles:true})
    await expect(page.getByRole('listbox')).toHaveCount(0)
    await expect(page.locator('.message-content')).toHaveCount(0)
    await input.dispatchEvent('compositionend')
    await expect(page.getByRole('listbox',{name:'Emoji suggestions'})).toHaveCount(0)
    await expect(input).toHaveValue(':sm')
    await input.fill(':smile:')
    await expect(input).toHaveValue(':smile:')
    await expect(page.getByRole('listbox')).toHaveCount(0)
  })

  test('large group suggestions scroll without moving the composer',async({page})=>{
    await page.goto('/')
    await page.getByRole('button',{name:'Go',exact:true}).click()
    for (let i=0;i<9;i++) {
      await page.getByRole('button',{name:'New Chat',exact:true}).click()
      await page.getByPlaceholder('Paste invite link').fill(nip19.npubEncode(getPublicKey(generateSecretKey())))
      await expect(page.getByPlaceholder('Type a message...')).toBeVisible()
      await page.getByRole('button',{name:'Back',exact:true}).click()
    }
    await page.getByRole('button',{name:'New Chat',exact:true}).click()
    await page.getByRole('button',{name:'Create Group',exact:true}).click()
    const create=page.getByTestId('create-group-view')
    await expect(create.getByTestId('create-group-member')).toHaveCount(9)
    for (const member of await create.getByTestId('create-group-member').all()) await member.click()
    await create.getByTestId('create-group-next').click()
    await page.getByPlaceholder('Enter group name...').fill('Weekend plans')
    await create.getByTestId('create-group-submit').click()
    const input=page.getByPlaceholder('Type a message...')
    await expect(input).toBeVisible()
    const frame=await input.boundingBox()
    await input.fill('@')
    const menu=page.getByRole('listbox',{name:'Mention someone'})
    await expect(menu.getByRole('option')).toHaveCount(10)
    for(let i=0;i<9;i++) await input.press('ArrowDown')
    await expect.poll(()=>menu.evaluate(el=>el.scrollTop)).toBeGreaterThan(0)
    await expect(menu.getByRole('option').last()).toBeInViewport()
    await expect.poll(()=>input.boundingBox()).toEqual(frame)
    const label=(await menu.getByRole('option').first().innerText()).trim()
    await input.fill(label)
    await expect.poll(()=>menu.evaluate(el=>el.scrollTop)).toBe(0)
    await menu.getByRole('option').first().tap()
    await expect(input).toHaveValue(label+' ')
    await expect(input).toBeFocused()
  })
})
